$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

$file = "d:\hama-daima\xiaoshanqing\app.html"
$content = [System.IO.File]::ReadAllText($file, [System.Text.Encoding]::UTF8)
$origLen = $content.Length
Write-Host "Original: $origLen chars"

# Pairs: start_marker, end_marker
$markers = @(
    @("// ==================== 全局配置常量 ====================", "// ==================== 数据持久化 ===================="),
    @("// ==================== 数据持久化 ====================", "// ==================== 深色模式 ===================="),
    @("// ==================== 深色模式 ====================", "// ==================== 语音播报 ===================="),
    @("// ==================== 语音播报 ====================", "// ==================== 分享功能 ===================="),
    @("// ==================== 分享功能 ====================", "// ==================== GPX 导入导出 ===================="),
    @("// ==================== GPX 导入导出 ====================", "// ==================== Service Worker 注册 ===================="),
    @("// ==================== Service Worker 注册 ====================", "// ==================== Web Worker 集成 ===================="),
    @("// ==================== Web Worker 集成 ====================", "// ==================== IndexedDB 集成 ===================="),
    @("// ==================== IndexedDB 集成 ====================", "// ==================== 紧急联系人管理 ===================="),
    @("// ==================== 紧急联系人管理 ====================", "// ==================== 首页 V2 管理器 ===================="),
    @("// ==================== 首页 V2 管理器 ====================", "// ==================== SOS 二次确认弹窗 ===================="),
    @("// ==================== V3 UI 初始化 ====================", "// ==================== Loading 遮罩 ===================="),
    @("// ==================== Loading 遮罩 ====================", "// ==================== Toast 通知 ===================="),
    @("// ==================== Toast 通知 ====================", "// ==================== 离线检测 ===================="),
    @("// ==================== 离线检测 ====================", "// ==================== 下拉刷新 ===================="),
    @("// ==================== 下拉刷新 ====================", "// ==================== 触摸滑动 ===================="),
    @("// ==================== 触摸滑动 ====================", "// ==================== 震动反馈 ===================="),
    @("// ==================== 震动反馈 ====================", "// ==================== 天气 API 接入 (WeatherAPI.com) ====================")
)

$removals = @()
foreach ($pair in $markers) {
    $s = $content.IndexOf($pair[0])
    $e = $content.IndexOf($pair[1])
    if ($s -ge 0 -and $e -gt $s) {
        $removals += ,@{s=$s; e=$e; l=$e-$s}
        Write-Host ("Found block at " + $s + "-" + $e + " len=" + ($e-$s))
    } else {
        Write-Host ("SKIP s=" + $s + " e=" + $e)
    }
}

Write-Host "Removing $($removals.Count) blocks from end to start..."
$removedTotal = 0
for ($i = $removals.Count-1; $i -ge 0; $i--) {
    $r = $removals[$i]
    $content = $content.Remove($r.s, $r.l)
    $removedTotal += $r.l
}

$newLen = $content.Length
Write-Host "Removed $removedTotal chars"
Write-Host "New size: $newLen (was $origLen)"
Write-Host "Saved: $($origLen - $newLen) chars"

[System.IO.File]::WriteAllText($file, $content, [System.Text.Encoding]::UTF8)
Write-Host "Written successfully"
