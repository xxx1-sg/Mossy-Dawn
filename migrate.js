/**
 * 模块化接入脚本
 * 移除 app.html 中已模块化的 JS 代码块
 */
const fs = require('fs');
const path = require('path');

const file = path.join(__dirname, 'app.html');
let content = fs.readFileSync(file, 'utf8');
const originalLen = content.length;
console.log('原始文件: ' + originalLen + ' chars');

// 要删除的块：[startMarker, endMarker]
const pairs = [
    ['// ==================== 全局配置常量 ====================', '// ==================== 数据持久化 ===================='],
    ['// ==================== 数据持久化 ====================', '// ==================== 深色模式 ===================='],
    ['// ==================== 深色模式 ====================', '// ==================== 语音播报 ===================='],
    ['// ==================== 语音播报 ====================', '// ==================== 分享功能 ===================='],
    ['// ==================== 分享功能 ====================', '// ==================== GPX 导入导出 ===================='],
    ['// ==================== GPX 导入导出 ====================', '// ==================== Service Worker 注册 ===================='],
    ['// ==================== Service Worker 注册 ====================', '// ==================== Web Worker 集成 ===================='],
    ['// ==================== Web Worker 集成 ====================', '// ==================== IndexedDB 集成 ===================='],
    ['// ==================== IndexedDB 集成 ====================', '// ==================== 紧急联系人管理 ===================='],
    ['// ==================== 紧急联系人管理 ====================', '// ==================== 首页 V2 管理器 ===================='],
    ['// ==================== 首页 V2 管理器 ====================', '// ==================== SOS 二次确认弹窗 ===================='],
    ['// ==================== V3 UI 初始化 ====================', '// ==================== Loading 遮罩 ===================='],
    ['// ==================== Loading 遮罩 ====================', '// ==================== Toast 通知 ===================='],
    ['// ==================== Toast 通知 ====================', '// ==================== 离线检测 ===================='],
    ['// ==================== 离线检测 ====================', '// ==================== 下拉刷新 ===================='],
    ['// ==================== 下拉刷新 ====================', '// ==================== 触摸滑动 ===================='],
    ['// ==================== 触摸滑动 ====================', '// ==================== 震动反馈 ===================='],
    ['// ==================== 震动反馈 ====================', '// ==================== 天气 API 接入 (WeatherAPI.com) ===================='],
];

// 收集所有要删除的位置（按 end 降序排列以避免索引偏移）
const removals = [];
for (const [start, end] of pairs) {
    const s = content.indexOf(start);
    const e = content.indexOf(end);
    if (s >= 0 && e > s) {
        removals.push({ s, e, len: e - s });
        console.log('  Found: "' + start.substring(4, 30) + '..." -> "' + end.substring(4, 30) + '..." (' + (e - s) + ' chars)');
    } else {
        console.log('  SKIP: "' + start.substring(4, 30) + '..." (s=' + s + ' e=' + e + ')');
    }
}

// 按 end 降序：从后往前删除
removals.sort((a, b) => b.e - a.e);
let totalRemoved = 0;
for (const r of removals) {
    content = content.slice(0, r.s) + content.slice(r.e);
    totalRemoved += r.len;
}

console.log('\n删除: ' + removals.length + ' 个块，共 ' + totalRemoved + ' 字符');
console.log('修改后: ' + content.length + ' chars (原始: ' + originalLen + ')');
console.log('减少: ' + (originalLen - content.length) + ' chars');

fs.writeFileSync(file, content, 'utf8');
console.log('\napp.html 已写入');
